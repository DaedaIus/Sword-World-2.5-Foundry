import assert from "node:assert/strict";
import { evasionSucceeded, staticAccuracy } from "../module/combat/evasion-challenge.mjs";
import { firstSide, playerInitiativeModifier, sideTransition } from "../module/combat/side-initiative.mjs";
import { deathCheckOutcome, deathCheckTarget } from "../module/rules/death-check.mjs";
import { isCriticalFailure } from "../module/rules/critical-failure.mjs";

assert.equal(staticAccuracy("5 (12)"), 12);
assert.equal(staticAccuracy("5"), null);
assert.equal(evasionSucceeded(12, 12), true);
assert.equal(evasionSucceeded(11, 12), false);
assert.equal(deathCheckTarget(-5), 5);
assert.equal(deathCheckTarget(0), 0);
assert.equal(deathCheckOutcome(5, 5, [2, 3]), "success");
assert.equal(deathCheckOutcome(4, 5, [2, 2]), "failure");
assert.equal(deathCheckOutcome(2, 20, [6, 6]), "automatic");
const diceRoll = results => ({ dice:[{ results:results.map(result => ({ result, active:true })) }] });
assert.equal(isCriticalFailure(diceRoll([1, 1])), true);
assert.equal(isCriticalFailure(diceRoll([1, 2])), false);
assert.equal(firstSide([9, 12, 7], 11), "players");
assert.equal(firstSide([9, 11], 11), "players");
assert.equal(firstSide([8, 10], 11), "monsters");
assert.equal(firstSide([], 5), "monsters");
assert.equal(playerInitiativeModifier(0, 0, 4), 0);
assert.equal(playerInitiativeModifier(3, 0, 4), 7);
assert.equal(playerInitiativeModifier(0, 5, 4), 9);
assert.equal(playerInitiativeModifier(3, 5, 4), 9);
assert.equal(playerInitiativeModifier(0, 0, 4, 2), 2);
assert.deepEqual(sideTransition("players", "players"), { phase:"monsters", newRound:false });
assert.deepEqual(sideTransition("players", "monsters"), { phase:"players", newRound:true });
assert.deepEqual(sideTransition("monsters", "monsters"), { phase:"players", newRound:false });
assert.deepEqual(sideTransition("monsters", "players"), { phase:"monsters", newRound:true });
console.log("Side initiative tests passed.");
